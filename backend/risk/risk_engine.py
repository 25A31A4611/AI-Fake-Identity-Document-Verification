def calculate_risk(
    validation_result,
    tampering_result,
    face_result,
    liveness_result,
    registry_result,
    cross_document_result=None
):
    """
    Calculate an overall prototype risk score.

    Score:
        0   = Lowest risk
        100 = Highest risk

    The risk score combines:
        1. Document validation
        2. Tampering detection
        3. Face verification
        4. Liveness detection
        5. Registry verification
        6. Cross-document consistency

    Important:
        - A document marked INVALID cannot become LOW RISK
          only because face/liveness checks passed.
        - A document marked REVIEW cannot silently become
          LOW RISK.
        - Cross-document mismatches increase the overall
          risk score using the risk points generated by
          the cross-document verification engine.
    """

    risk_score = 0
    reasons = []

    # Transparent contribution tracking.
    # These values mirror the existing scoring rules so the final
    # assessment can explain exactly where risk points came from.
    validation_contribution = 0
    face_contribution = 0
    liveness_contribution = 0
    registry_contribution = 0
    cross_document_risk_points = 0

    # =========================================
    # 1. DOCUMENT VALIDATION
    # =========================================

    validation_score = validation_result.get(
        "score",
        0
    )

    validation_status = str(
        validation_result.get(
            "status",
            "REVIEW"
        )
    ).upper()

    document_is_invalid = False
    document_needs_review = False

    if validation_status == "VALID":

        validation_contribution = 0
        risk_score += validation_contribution

    elif validation_status == "REVIEW":

        validation_contribution = 25
        risk_score += validation_contribution
        document_needs_review = True

        reasons.append(
            "Document validation requires manual verification "
            "because one or more expected fields or checks "
            "could not be confirmed."
        )

    elif validation_status == "INVALID":

        validation_contribution = 55
        risk_score += validation_contribution
        document_is_invalid = True

        reasons.append(
            "Document validation failed because required "
            "information or document-type checks were not satisfied."
        )

    else:

        validation_contribution = 40
        risk_score += validation_contribution
        document_needs_review = True

        reasons.append(
            "Document validation returned an unknown status "
            "and requires manual verification."
        )

    # =========================================
    # 2. DOCUMENT VALIDATION SCORE INFORMATION
    # =========================================

    try:
        validation_score_numeric = float(
            validation_score
        )
    except (TypeError, ValueError):
        validation_score_numeric = 0

    if validation_status == "VALID":

        if validation_score_numeric < 60:

            validation_contribution += 10
            risk_score += 10

            reasons.append(
                f"Document validation score is "
                f"{validation_score_numeric:.0f}/100, "
                f"which is relatively low."
            )

    elif validation_status == "REVIEW":

        if validation_score_numeric < 50:

            validation_contribution += 10
            risk_score += 10

            reasons.append(
                f"Document validation score is "
                f"{validation_score_numeric:.0f}/100."
            )

    # =========================================
    # 3. TAMPERING DETECTION
    # =========================================

    tampering_score = tampering_result.get(
        "score",
        50
    )

    tampering_status = str(
        tampering_result.get(
            "status",
            "REVIEW"
        )
    ).upper()

    try:
        tampering_score_numeric = float(
            tampering_score
        )
    except (TypeError, ValueError):
        tampering_score_numeric = 50

    tampering_contribution = round(
        tampering_score_numeric * 0.40
    )

    risk_score += tampering_contribution

    if tampering_status == "HIGH RISK":

        reasons.append(
            "Image-level analysis detected significant "
            "signals associated with possible document manipulation."
        )

    elif tampering_status == "MEDIUM RISK":

        reasons.append(
            "Image-level analysis detected moderate "
            "inconsistencies that require review."
        )

    elif tampering_status == "REVIEW":

        reasons.append(
            "Tampering analysis produced an uncertain result "
            "and requires additional verification."
        )

    elif tampering_status == "LOW RISK":

        pass

    # =========================================
    # 4. FACE VERIFICATION
    # =========================================

    face_status = str(
        face_result.get(
            "status",
            "NOT PROVIDED"
        )
    ).upper()

    face_score = face_result.get(
        "score",
        0
    )

    try:
        face_score_numeric = float(
            face_score
        )
    except (TypeError, ValueError):
        face_score_numeric = 0

    if face_status == "MATCH":

        face_contribution = -20
        risk_score += face_contribution

    elif face_status == "NO MATCH":

        face_contribution = 40
        risk_score += face_contribution

        reasons.append(
            "The verification face did not meet "
            "the prototype identity-matching threshold."
        )

    elif face_status == "REVIEW":

        face_contribution = 20
        risk_score += face_contribution

        reasons.append(
            "Face verification could not be completed "
            "with sufficient confidence."
        )

    elif face_status == "NOT PROVIDED":

        face_contribution = 15
        risk_score += face_contribution

        reasons.append(
            "No verification face image was provided."
        )

    else:

        face_contribution = 20
        risk_score += face_contribution

        reasons.append(
            "Face verification returned an uncertain "
            "or unsupported result."
        )

    # =========================================
    # 5. FACE SCORE INFORMATION
    # =========================================

    if face_status == "MATCH":

        reasons.append(
            f"Face verification produced a similarity "
            f"score of {face_score_numeric:.2f}/100."
        )

    elif face_status == "NO MATCH":

        reasons.append(
            f"Face verification produced a similarity "
            f"score of {face_score_numeric:.2f}/100."
        )

    # =========================================
    # 6. LIVENESS DETECTION
    # =========================================

    liveness_status = str(
        liveness_result.get(
            "status",
            "NOT PROVIDED"
        )
    ).upper()

    liveness_score = liveness_result.get(
        "score",
        0
    )

    try:
        liveness_score_numeric = float(
            liveness_score
        )
    except (TypeError, ValueError):
        liveness_score_numeric = 0

    if liveness_status == "LIVE":

        liveness_contribution = -10
        risk_score += liveness_contribution

        reasons.append(
            f"Liveness analysis produced a live-person "
            f"signal with a score of "
            f"{liveness_score_numeric:.2f}/100."
        )

    elif liveness_status == "SPOOF":

        liveness_contribution = 40
        risk_score += liveness_contribution

        reasons.append(
            "Liveness analysis detected weak signals "
            "that may indicate a spoofed or low-quality "
            "verification image."
        )

    elif liveness_status == "REVIEW":

        liveness_contribution = 20
        risk_score += liveness_contribution

        reasons.append(
            "Liveness verification produced an uncertain "
            "result and requires additional verification."
        )

    elif liveness_status == "NOT PROVIDED":

        liveness_contribution = 15
        risk_score += liveness_contribution

        reasons.append(
            "No liveness verification image was provided."
        )

    else:

        liveness_contribution = 20
        risk_score += liveness_contribution

        reasons.append(
            "Liveness verification returned an uncertain "
            "or unsupported result."
        )

    # =========================================
    # 7. REGISTRY VERIFICATION
    # =========================================

    registry_status = str(
        registry_result.get(
            "status",
            "REVIEW"
        )
    ).upper()

    if registry_status == "VERIFIED":

        registry_contribution = 0

        reasons.append(
            "Registry verification confirmed that "
            "the extracted document information matches "
            "the authorized registry record."
        )

    elif registry_status == "MISMATCH":

        registry_contribution = 30
        risk_score += registry_contribution

        reasons.append(
            "Registry verification detected one or more "
            "fields that do not match the authorized "
            "registry record."
        )

    elif registry_status == "NOT FOUND":

        registry_contribution = 50
        risk_score += registry_contribution

        reasons.append(
            "No matching authorized registry record "
            "was found for the document."
        )

    elif registry_status == "REVIEW":

        registry_contribution = 20
        risk_score += registry_contribution

        reasons.append(
            "Registry verification could not be completed "
            "automatically and requires manual verification."
        )

    else:

        registry_contribution = 20
        risk_score += registry_contribution

        reasons.append(
            "Registry verification returned an unknown "
            "status and requires manual verification."
        )

    # =========================================
    # 8. CROSS-DOCUMENT CONSISTENCY
    # =========================================

    # Cross-document verification is optional.
    #
    # If no second document was uploaded,
    # this contributes 0 risk.
    #
    # If documents contain mismatching identity
    # fields, use the risk_points generated by
    # cross_document.py.

    if cross_document_result is None:

        cross_document_status = "NOT PROVIDED"
        cross_document_risk_points = 0

    else:

        cross_document_status = str(
            cross_document_result.get(
                "status",
                "NOT PROVIDED"
            )
        ).upper()

        try:
            cross_document_risk_points = int(
                cross_document_result.get(
                    "risk_points",
                    0
                )
            )
        except (TypeError, ValueError):

            cross_document_risk_points = 0

    # Prevent invalid negative values from affecting
    # the risk calculation.

    cross_document_risk_points = max(
        0,
        cross_document_risk_points
    )

    if cross_document_status == "CONSISTENT":

        reasons.append(
            "Cross-document verification found consistent "
            "identity information across the supplied documents."
        )

    elif cross_document_status == "MISMATCH":

        risk_score += cross_document_risk_points

        mismatched_fields = cross_document_result.get(
            "mismatched_fields",
            []
        ) if cross_document_result else []

        if mismatched_fields:

            formatted_fields = ", ".join(
                str(field)
                for field in mismatched_fields
            )

            reasons.append(
                "Cross-document verification detected "
                f"identity field mismatches: {formatted_fields}."
            )

        else:

            reasons.append(
                "Cross-document verification detected "
                "inconsistent identity information."
            )

        reasons.append(
            f"Cross-document consistency contributed "
            f"{cross_document_risk_points} risk points."
        )

    elif cross_document_status == "REVIEW":

        reasons.append(
            "Cross-document verification could not be completed "
            "with sufficient confidence and requires manual review."
        )

    elif cross_document_status == "NOT PROVIDED":

        pass

    else:

        reasons.append(
            "Cross-document verification returned an uncertain "
            "or unsupported result."
        )

    # Capture the component-based score before any safety floors.
    # Safety rules can raise the final score without changing the
    # underlying component contributions.
    component_risk_score = risk_score

    # =========================================
    # 9. SAFETY RULES
    # =========================================

    if document_is_invalid:

        risk_score = max(
            risk_score,
            70
        )

    elif document_needs_review:

        risk_score = max(
            risk_score,
            40
        )

    # =========================================
    # REGISTRY SAFETY RULES
    # =========================================

    if registry_status == "MISMATCH":

        risk_score = max(
            risk_score,
            40
        )

    elif registry_status == "NOT FOUND":

        risk_score = max(
            risk_score,
            50
        )

    elif registry_status == "REVIEW":

        risk_score = max(
            risk_score,
            40
        )

    # =========================================
    # CROSS-DOCUMENT SAFETY RULE
    # =========================================

    if cross_document_status == "MISMATCH":

        # A confirmed identity mismatch should not
        # disappear because other checks passed.

        risk_score = max(
            risk_score,
            40
        )

    # Any increase caused only by a mandatory safety floor is
    # reported separately so the contribution breakdown remains
    # mathematically transparent.
    safety_floor_adjustment = max(
        0,
        risk_score - component_risk_score
    )

    # =========================================
    # 10. KEEP SCORE BETWEEN 0 AND 100
    # =========================================

    risk_score = max(
        0,
        min(
            100,
            int(round(risk_score))
        )
    )

    # =========================================
    # 11. DETERMINE RISK LEVEL
    # =========================================

    if risk_score >= 70:

        risk_level = "HIGH RISK"

    elif risk_score >= 40:

        risk_level = "MEDIUM RISK"

    else:

        risk_level = "LOW RISK"

    # =========================================
    # 12. DEFAULT MESSAGE
    # =========================================

    if not reasons:

        reasons.append(
            "No major anomalies were detected "
            "during the current prototype screening."
        )

    # =========================================
    # 13. RETURN RESULT
    # =========================================

    return {
        "score": risk_score,
        "level": risk_level,
        "reasons": reasons,
        "validation_score": validation_score,
        "tampering_score": tampering_score,
        "face_score": face_score,
        "liveness_score": liveness_score,
        "registry_status": registry_status,
        "registry_contribution": registry_contribution,
        "cross_document_status": cross_document_status,
        "cross_document_risk_points": cross_document_risk_points,
        "risk_breakdown": {
            "document_validation": validation_contribution,
            "tampering": tampering_contribution,
            "face_verification": face_contribution,
            "liveness": liveness_contribution,
            "registry": registry_contribution,
            "cross_document": cross_document_risk_points,
            "safety_floor_adjustment": safety_floor_adjustment
        }
    }